using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Pharos.Server.Domain;
using Pharos.Server.Domain.Enums;

namespace Pharos.Server.Sample.Domain;

/// <summary>
/// Represents a sample tube.
/// </summary>
internal class SampleTube : BaseEntity
{
    public const int ImageIdentityLength = 64;

    /// <summary>
    /// The unique tube ID assigned by Pharos and shared with the instrument.
    /// If the value is null the tube is not identified.
    /// </summary>
    [MaxLength(Constants.TubeIdMaxLength)]
    public string? TubeId { get; set; }

    /// <summary>
    /// The serial number of the instrument where the tube was or is currently located.
    /// </summary>
    [MaxLength(Constants.InstrumentSerialNumberLength)]
    public string? InstrumentNumber { get; set; }

    /// <summary>
    /// The time when this tube was loaded to the instrument and detected by it.
    /// </summary>
    public DateTimeOffset? LoadTimestamp { get; set; }

    /// <summary>
    /// The unique sample ID that is visible to the user. If the value is null the tube is not identified.
    /// </summary>
    [MaxLength(Constants.SampleIdMaxLength)]
    public string? SampleId { get; set; }

    /// <summary>
    /// The sample ID suffix encoded in the tube barcode. Used as a tube ID visible to the end user.
    /// </summary>
    [MaxLength(Constants.SampleIdMaxLength)]
    public string? SampleIdSuffix { get; set; }

    /// <summary>
    /// The way that tube ha been identified.
    /// </summary>
    public SampleTubeIdentitySource IdentitySource { get; set; }

    /// <summary>
    /// The request creation date. This property is needed if the sample ID is non-unique
    /// If the value is null this means that the tube is either not identified or request
    /// is not created yet.
    /// </summary>
    public DateTimeOffset? RequestCreatedDate { get; set; }

    /// <summary>
    /// Is High Priority set to the tube.
    /// </summary>
    public bool HighPriority { get; set; }

    /// <summary>
    /// The status of the tube that is currently in the instrument.
    /// </summary>
    public SampleTubeStatus Status { get; set; }

    /// <summary>
    /// Indicates that an unload operation has been requested for this tube from Pharos.
    /// </summary>
    public bool UnloadRequested { get; set; }

    /// <summary>
    /// The main error of the tube.
    /// </summary>
    public SampleTubeError Error => InternalError != SampleTubeError.None ? InternalError : InstrumentError;

    /// <summary>
    /// The sample tube error detected by the instrument.
    /// </summary>
    public SampleTubeError InstrumentError { get; set; }

    /// <summary>
    /// The internal Pharos error for the tube.
    /// </summary>
    public SampleTubeError InternalError { get; set; }

    /// <summary>
    /// The sample volume in the tube when this tube was unloaded from the instrument.
    /// </summary>
    public double SampleVolume { get; set; }

    /// <summary>
    /// The identifier of the image(s). Generated by the instrument at the time the image(s) was taken.
    /// </summary>
    [MaxLength(ImageIdentityLength)]
    public string? ImageIdentity { get; set; }

    /// <summary>
    /// The ID of the tray in which the sample tube is located.
    /// </summary>
    [MaxLength(Constants.TrayIdLength)]
    public string? TrayId { get; set; }

    /// <summary>
    /// The position of the sample tube in the tray.
    /// </summary>
    public int? TubePosition { get; set; }

    /// <summary>
    /// The barcode read by the instrument from the sample tube. The value ie empty if the
    /// tube has no barcode, or it cannot be read.
    ///  </summary>
    [MaxLength(Constants.TubeBarcodeMaxLength)]
    public string? TubeBarcode { get; set; }

    /// <summary>
    /// The sample type - whether it is QC or Sample
    /// </summary>
    public SampleType SampleType { get; set; }

    /// <summary>
    /// Sample tube possible locations {SampleDrawer1, SampleDrawer2, InternalStorage, Shuttle1, Shuttle2 }
    /// </summary>
    [NotMapped]
    public SampleArea Area { get; set; }

    /// <summary>
    /// The tray position in the sample drawer. THis field is used for in-memory storage processing.
    /// </summary>
    [NotMapped]
    public int? TrayPosition { get; set; }

    /// <summary>
    /// Number of mm from bottom, 0 if no gel detected.
    /// 
    /// Can be used to determine if the tube is primary or secondary to be shown in Pharos
    /// (otherwise the value will also be kept in a log file for investigation purposes).
    ///  </summary>
    [NotMapped]
    public int GelSeparatorLayer { get; set; } = 0;

    /// <summary>
    ///  OriginalPosition is required to retain position of the tubes defined by external source (LIS, File Import)
    /// </summary>
    [NotMapped]
    public OriginalPosition? OriginalPosition { get; set; }

}

/// <summary>
/// Represents the original position of a sample tube in the instrument storage.
/// </summary>
public class OriginalPosition
{
    public SampleArea Area { get; set; }

    public int? TrayPosition { get; set; }

    [MaxLength(Constants.TrayIdLength)]
    public string? TrayId { get; set; }

    public int? TubePosition { get; set; }
}