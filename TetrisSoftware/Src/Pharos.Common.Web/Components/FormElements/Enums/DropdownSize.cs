namespace Pharos.Common.Web.Components.FormElements.Enums;

public enum DropdownSize
{
    /// <summary>
    /// Non-fixed size. Can be flexed.
    /// </summary>
    Default,
    /// <summary>
    /// Fit the widest option text inside the dropdown.
    /// </summary>
    FitContent,
    /// <summary>
    /// A fixed standard input size for having equal width input fields.
    /// </summary>
    SmallInputWidth,
    MediumInputWidth,
    LargeInputWidth,
}