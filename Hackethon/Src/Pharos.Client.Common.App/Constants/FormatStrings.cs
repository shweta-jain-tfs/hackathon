namespace Pharos.Client.Common.App.Constants;

/// <summary>
/// Aliases for common format strings used in the application.
/// </summary>
public static class FormatStrings
{
    /// <summary>
    /// year, month , day
    /// </summary>
    public const string ShortDate = "d";

    /// <summary>
    /// hour, minute
    /// </summary>
    public const string ShortTime = "t";

    /// <summary>
    /// year, month, day, hour, minute
    /// </summary>
    public const string ShortDateTime = "g";

    /// <summary>
    /// year, month, day, hour, minute in explicit format
    /// </summary>
    public const string SortableDateTime = "yyyy-MM-dd HH:mm";

}
